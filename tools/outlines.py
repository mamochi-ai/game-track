"""Compute convex collision parts from sprite alpha (transparent pixels excluded).

Each sprite is split into rectangular regions and each region's convex hull
is simplified to <= MAXV vertices. Output: assets/sprites/outlines.json with
normalized coords (x right, y down, origin at sprite center, units = sprite w/h).
"""
import json
import numpy as np
from PIL import Image

MAXV = 8
# Each part is a rectangle (x0, x1, y0, y1) in sprite fractions; the hull of the
# opaque pixels inside it becomes one convex fixture. None = circle.
FULL = [(0, 1, 0, 1)]
REGIONS = {
    'box': FULL,
    'fridge': FULL,
    'sofa': [(0, 1, 0, 0.25), (0, 1, 0.25, 1)],          # backrest / arms + seat
    'cat': [(0, 0.74, 0, 0.42), (0.74, 1, 0, 0.40), (0, 1, 0.40, 1)],  # head / raised paw / body
    'plank': FULL,
    'tire': None,
}


def hull(pts):
    pts = sorted(set(map(tuple, pts)))
    if len(pts) < 3:
        return pts
    def cross(o, a, b):
        return (a[0]-o[0])*(b[1]-o[1]) - (a[1]-o[1])*(b[0]-o[0])
    lo, up = [], []
    for p in pts:
        while len(lo) >= 2 and cross(lo[-2], lo[-1], p) <= 0:
            lo.pop()
        lo.append(p)
    for p in reversed(pts):
        while len(up) >= 2 and cross(up[-2], up[-1], p) <= 0:
            up.pop()
        up.append(p)
    return lo[:-1] + up[:-1]


def simplify(poly, maxv):
    """Visvalingam on a convex polygon; then push edges outward slightly is skipped (keeps fit tight)."""
    poly = list(poly)
    def area(a, b, c):
        return abs((b[0]-a[0])*(c[1]-a[1]) - (c[0]-a[0])*(b[1]-a[1])) / 2
    while len(poly) > maxv:
        n = len(poly)
        ar = [area(poly[i-1], poly[i], poly[(i+1) % n]) for i in range(n)]
        poly.pop(int(np.argmin(ar)))
    return poly


out = {}
for name, regions in REGIONS.items():
    a = np.array(Image.open(f'assets/sprites/{name}.png'))[:, :, 3] > 110
    h, w = a.shape
    ys, xs = np.nonzero(a)
    entry = {'w': w, 'h': h}
    if regions is None:
        cx, cy = (xs.min()+xs.max()+1)/2, (ys.min()+ys.max()+1)/2
        r = max(xs.max()+1-xs.min(), ys.max()+1-ys.min())/2
        entry['circle'] = {'x': (cx-w/2)/w, 'y': (cy-h/2)/h, 'r': r/w}
    else:
        parts = []
        for fx0, fx1, fy0, fy1 in regions:
            x0, x1, y0, y1 = int(fx0*w), int(fx1*w), int(fy0*h), int(fy1*h)
            sel = (xs >= x0) & (xs < x1) & (ys >= y0) & (ys < y1)
            # use pixel corners so the hull covers whole pixels
            px = np.concatenate([xs[sel], xs[sel]+1, xs[sel], xs[sel]+1])
            py = np.concatenate([ys[sel], ys[sel], ys[sel]+1, ys[sel]+1])
            hp = simplify(hull(np.stack([px, py], 1)), MAXV)
            parts.append([[round((x-w/2)/w, 4), round((y-h/2)/h, 4)] for x, y in hp])
        entry['parts'] = parts
    out[name] = entry
json.dump(out, open('assets/sprites/outlines.json', 'w'), indent=1)

with open('js/outlines.js', 'w') as f:
    f.write('// Generated by tools/outlines.py - collision outlines traced from sprite alpha.\n')
    f.write('window.OUTLINES = ' + json.dumps(out) + ';\n')
